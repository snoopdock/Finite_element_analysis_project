def extract_llm_text(
    response: Any,
    provider: str = "unknown",
    model: str = "unknown",
    verbose: bool = False,
) -> Optional[str]:
    """
    Quick convenience function to extract LLM text from an API response.
    
    Example:
        >>> from llms_response_extractor import extract_llm_text
        >>> text = extract_llm_text(api_response, provider="cloudflare")
    """
    extractor = LLMResponseExtractor(verbose=verbose)
    return extractor.extract(response, provider=provider, model=model)
